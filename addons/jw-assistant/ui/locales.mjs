export function message(locale, key, values = {}) {
  const catalog = catalogs[locale] || catalogs["ja-JP"];
  const raw = key.split(".").reduce((value, part) => value && value[part], catalog) ?? key;
  return String(raw).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}
